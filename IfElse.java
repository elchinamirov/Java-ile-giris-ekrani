public class IfElse {
    public static void main(String [] args){
        int x=10;
        if(x<10){
            System.out.println("x-in qiymeti 10-dan kicik ededdir");
        }
        if(x>10){
            System.out.println("x ededi 10-dan boyukdur");
        }
        if(x==10){
            System.out.println("x ededi 10-a beraberdir");
        }

        else{
            System.out.println("x-in qiymeti 10-dan kicik deyil");
        }
    }
}
